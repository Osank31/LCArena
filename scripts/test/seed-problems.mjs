#!/usr/bin/env node
/**
 * Seed a handful of sample problems into MongoDB.
 *
 *   npm run seed:problems
 *   npm run seed:problems -- --url=mongodb://127.0.0.1:27018/lcarena_test
 *   npm run seed:problems -- --count=50
 *   npm run seed:problems -- --dry-run
 *
 * Idempotent: every document this script writes is tagged with a
 * `https://seed.lcarena.local/...` test-case URL, and a re-run replaces exactly
 * those documents. It never touches problems created through the API.
 *
 * Useful before running the load tests, which need a real problem id:
 *   TEST_PROBLEM_ID=<printed id> npm run test:load -- --profile=smoke
 */
import { MongoClient } from "mongodb";

const args = process.argv.slice(2);
const valueOf = (flag) => {
    const match = args.find((arg) => arg.startsWith(`${flag}=`));
    if (match) return match.slice(flag.length + 1);

    const index = args.indexOf(flag);
    if (index !== -1 && args[index + 1] && !args[index + 1].startsWith("--")) {
        return args[index + 1];
    }

    return undefined;
};

if (args.includes("--help") || args.includes("-h")) {
    console.log(
        "Usage: node scripts/test/seed-problems.mjs [--url=<mongo-url>] [--count=<n>] [--dry-run]"
    );
    process.exit(0);
}

const MONGO_URL =
    valueOf("--url") || process.env.MONGODB_URL || "mongodb://127.0.0.1:27017/lcarena";
const count = Number(valueOf("--count") || 3);
const dryRun = args.includes("--dry-run");

if (!Number.isInteger(count) || count < 1 || count > 500) {
    console.error(`[seed] --count must be an integer between 1 and 500 (got "${valueOf("--count")}")`);
    process.exit(2);
}

const SEED_ORIGIN = "https://seed.lcarena.local";

const BLUEPRINTS = [
    {
        slug: "sum-of-two-integers",
        description:
            "Read two integers from standard input and print their sum. " +
            "A warm-up problem used to check that compilation and I/O work end to end.",
        difficulty: "Easy",
        time_limit: 2000,
    },
    {
        slug: "count-inversions",
        description:
            "Given an array of integers, count the number of inversions (pairs i < j " +
            "with a[i] > a[j]). Aim for O(n log n) with a merge sort or a Fenwick tree.",
        difficulty: "Medium",
        time_limit: 4000,
    },
    {
        slug: "shortest-path-queries",
        description:
            "Answer shortest-path queries on a weighted undirected graph with up to " +
            "2 * 10^5 vertices. Rebuild the data structure between test cases within the time limit.",
        difficulty: "Hard",
        time_limit: 5000,
    },
];

const pad = (index) => String(index + 1).padStart(3, "0");

const buildProblem = (index) => {
    const blueprint = BLUEPRINTS[index % BLUEPRINTS.length];

    return {
        description:
            `${blueprint.description}\n\n[seed ${pad(index)}] Generated by scripts/test/seed-problems.mjs.`,
        difficulty: blueprint.difficulty,
        sampleTestCaseUrl: `${SEED_ORIGIN}/${blueprint.slug}/sample.txt`,
        testCasesUrl: `${SEED_ORIGIN}/${blueprint.slug}/testcases.zip`,
        time_limit: blueprint.time_limit,
    };
};

const main = async () => {
    const problems = Array.from({ length: count }, (_, index) =>
        buildProblem(index)
    );

    if (dryRun) {
        console.log(
            `[seed] dry run: would replace seeded problems with ${problems.length} document(s):`
        );
        for (const problem of problems.slice(0, 10)) {
            console.log(`  - [${problem.difficulty}] ${problem.testCasesUrl}`);
        }
        if (problems.length > 10) console.log(`  ... and ${problems.length - 10} more`);
        return;
    }

    const client = new MongoClient(MONGO_URL, { serverSelectionTimeoutMS: 5000 });

    try {
        await client.connect();
    } catch (error) {
        console.error(`[seed] could not connect to ${MONGO_URL}: ${error.message}`);
        console.error(
            "[seed] is MongoDB running? Try `npm run docker:up` (development stack) or " +
                "`docker compose -p lcarena-test -f docker-compose.test.yml up -d --wait` (isolated)."
        );
        process.exit(1);
    }

    try {
        const collection = client.db().collection("problems");
        const now = new Date();

        // Replace only the documents this script created before.
        const removed = await collection.deleteMany({
            sampleTestCaseUrl: { $regex: `^${SEED_ORIGIN}` },
        });

        const documents = problems.map((problem) => ({
            ...problem,
            createdAt: now,
            updatedAt: now,
        }));

        const inserted = await collection.insertMany(documents);

        console.log(
            `[seed] database: ${client.db().databaseName} — removed ${removed.deletedCount}, inserted ${inserted.insertedCount}`
        );

        const ids = Object.values(inserted.insertedIds).map(String);
        console.log("[seed] problem ids:");
        for (const id of ids) console.log(`  ${id}`);

        console.log(
            `\n[seed] use one as TEST_PROBLEM_ID for the load tests:\n  TEST_PROBLEM_ID=${ids[0]} npm run test:load -- --profile=smoke`
        );
    } finally {
        await client.close();
    }
};

main().catch((error) => {
    console.error("[seed] unexpected failure:", error);
    process.exit(1);
});
